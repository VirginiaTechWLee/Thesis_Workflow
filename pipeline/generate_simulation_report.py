def find_captured_images(run_folder):
    """Find captured FEM screenshot PNGs."""
    manifest = os.path.join(run_folder, "captured_images.txt")
    if os.path.isfile(manifest):
        with open(manifest, 'r') as f:
            paths = [line.strip() for line in f if line.strip()]
        return [p for p in paths if os.path.isfile(p)]

    known_images = [
        "mesh_overview.png", "boundary_conditions.png",
        "mode_shape_01.png", "mode_shape_02.png", "mode_shape_03.png",
        "cbush_locations.png", "frequency_bar_chart.png", "psd_response.png",
    ]
    found = []
    for name in known_images:
        path = os.path.join(run_folder, name)
        if os.path.isfile(path):
            found.append(path)
    return found


