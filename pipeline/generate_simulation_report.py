"""
Generate an LLFEM-branded simulation report from Nastran F06 output.

LLFEM = LLM-generated FEM report. All AI-generated content is clearly marked
with LLFEM branding so readers know the report was written by AI.

Reads F06 files, calls Anthropic API with grounded system prompt (no outside
knowledge), embeds FEM screenshots, and outputs DOCX + PDF.

Usage:
    python pipeline/generate_simulation_report.py --run-folder <path>
    python pipeline/generate_simulation_report.py --run-folder <path> --skip-llm
    python pipeline/generate_simulation_report.py --f06 <path> --output <path>

Requires:
    ANTHROPIC_API_KEY environment variable (unless --skip-llm)
    pip install anthropic python-docx docx2pdf Pillow
"""

import sys
import os
import argparse
import glob as globmod
import re
import datetime


# ---------------------------------------------------------------------------
# LLFEM Branding Constants
# ---------------------------------------------------------------------------
LLFEM_TAG = "LLFEM"
LLFEM_FULL = "LLFEM — LLM-Generated FEM Analysis Report"
LLFEM_DISCLAIMER = (
    "This report was generated by an AI model (Claude, Anthropic) analyzing "
    "only the provided Nastran F06 output data. The AI was instructed to use "
    "no outside knowledge. All conclusions are derived solely from the data "
    "provided. Human review is recommended before making engineering decisions."
)


# ---------------------------------------------------------------------------
# F06 Parsing
# ---------------------------------------------------------------------------
def find_f06_files(run_folder):
    """Find all F06 files in the run folder."""
    matches = globmod.glob(os.path.join(run_folder, '*.f06')) + \
              globmod.glob(os.path.join(run_folder, '*.F06'))
    seen = set()
    unique = []
    for path in sorted(matches):
        norm = os.path.normcase(os.path.normpath(path))
        if norm not in seen:
            seen.add(norm)
            unique.append(path)
    return unique


def extract_f06_summary(f06_path, max_chars=80000):
    """Read F06 and extract key sections within token limits."""
    with open(f06_path, 'r', errors='ignore') as f:
        content = f.read()

    if len(content) <= max_chars:
        return content

    sections = []
    lines = content.split('\n')

    # Header
    sections.append('\n'.join(lines[:200]))

    # Eigenvalue tables
    for pattern in [r'R E A L   E I G E N V A L U E S.*?(?=\n\s*\n|\x0c)',
                    r'EIGENVALUE.*?(?=\n\s*\n|\x0c)']:
        matches = re.findall(pattern, content, re.DOTALL | re.IGNORECASE)
        for m in matches[:3]:
            sections.append(m[:5000])

    # FATAL and WARNING messages
    for line_num, line in enumerate(lines):
        if re.search(r'(FATAL|WARNING|USER INFORMATION)', line, re.IGNORECASE):
            start = max(0, line_num - 2)
            end = min(len(lines), line_num + 5)
            sections.append('\n'.join(lines[start:end]))

    # Tail
    sections.append('\n'.join(lines[-100:]))

    combined = '\n\n--- [section break] ---\n\n'.join(sections)
    return combined[:max_chars]


# ---------------------------------------------------------------------------
# LLM Report Generation
# ---------------------------------------------------------------------------
def generate_report(f06_content, f06_filename):
    """Call Anthropic API to generate simulation report."""
    try:
        import anthropic
    except ImportError:
        print("ERROR: anthropic package not installed. Run: pip install anthropic")
        sys.exit(1)

    api_key = os.environ.get('ANTHROPIC_API_KEY')
    if not api_key:
        print("ERROR: ANTHROPIC_API_KEY environment variable not set")
        sys.exit(1)

    client = anthropic.Anthropic(api_key=api_key)

    system_prompt = (
        "You are a Nastran simulation analyst generating an LLFEM report. "
        "Analyze ONLY the F06 content provided to you in this message. "
        "Do not use any outside knowledge about Nastran, spacecraft, or structural "
        "analysis. If the data does not support a conclusion, say so explicitly. "
        "Never invent frequencies, results, or conclusions not present in the "
        "provided data. Flag any FATAL errors, list natural frequencies, summarize "
        "random response results, and state whether the model is healthy and "
        "DBALL-ready. Use clear section headers with ## markdown syntax."
    )

    user_prompt = (
        f"Analyze this Nastran F06 output file ({f06_filename}) and produce a "
        "simulation report with these sections:\n\n"
        "1. **Model Summary** — nodes, elements, CBUSH count, boundary conditions\n"
        "2. **Natural Frequencies** — first 10 modes with frequencies in Hz\n"
        "3. **Warnings and Fatals** — any FATAL or WARNING messages\n"
        "4. **DBALL Chain Status** — did SOL 103 and/or SOL 111 complete cleanly\n"
        "5. **Random Response Summary** — peak PSD values, dominant frequencies (if present)\n"
        "6. **Health Assessment** — is this FEM ready for the super workflow?\n\n"
        "--- BEGIN F06 CONTENT ---\n"
        f"{f06_content}\n"
        "--- END F06 CONTENT ---"
    )

    print("Calling Anthropic API (model: claude-sonnet-4-20250514)...")
    message = client.messages.create(
        model="claude-sonnet-4-20250514",
        max_tokens=4096,
        temperature=0,
        system=system_prompt,
        messages=[{"role": "user", "content": user_prompt}]
    )

    return message.content[0].text


