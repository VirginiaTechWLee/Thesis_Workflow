# DOCX Report Writer
# ---------------------------------------------------------------------------
def write_docx_report(output_path, report_text, f06_filename, images, run_folder):
    """Write LLFEM-branded simulation report as DOCX with inline images."""
    try:
        from docx import Document
        from docx.shared import Inches, Pt, RGBColor, Cm, Emu
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.enum.section import WD_ORIENT
    except ImportError:
        print("WARNING: python-docx not installed, falling back to .md")
        return False

    doc = Document()

    # ── Style setup ──
    style = doc.styles['Normal']
    font = style.font
    font.name = 'Calibri'
    font.size = Pt(11)

    # ── Cover Page ──
    # LLFEM badge
    llfem_para = doc.add_paragraph()
    llfem_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    llfem_run = llfem_para.add_run(f"[ {LLFEM_TAG} ]")
    llfem_run.bold = True
    llfem_run.font.size = Pt(28)
    llfem_run.font.color.rgb = RGBColor(0x25, 0x63, 0xEB)

    # Spacer
    doc.add_paragraph()

    # Title
    title = doc.add_heading("Nastran Simulation Report", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Subtitle
    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub_run = sub.add_run("AI-Generated Structural Analysis Report")
    sub_run.font.size = Pt(14)
    sub_run.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)

    doc.add_paragraph()

    # Metadata table
    now = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    meta_items = [
        ("Generated", now),
        ("F06 Files", f06_filename),
        ("Generator", "Claude (Anthropic API, temperature=0)"),
        ("Report Type", LLFEM_FULL),
        ("FEM Images", f"{len(images)} screenshots embedded" if images else "None"),
    ]
    table = doc.add_table(rows=len(meta_items), cols=2)
    table.style = 'Light Grid Accent 1'
    for i, (key, val) in enumerate(meta_items):
        row = table.rows[i]
        row.cells[0].text = key
        row.cells[1].text = val
        # Bold keys
        for paragraph in row.cells[0].paragraphs:
            for run in paragraph.runs:
                run.bold = True

    doc.add_paragraph()

    # LLFEM Disclaimer box
    disclaimer = doc.add_paragraph()
    disclaimer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    d_run = disclaimer.add_run(f"⚠ {LLFEM_TAG} DISCLAIMER\n")
    d_run.bold = True
    d_run.font.size = Pt(10)
    d_run.font.color.rgb = RGBColor(0xDC, 0x26, 0x26)
    d_run2 = disclaimer.add_run(LLFEM_DISCLAIMER)
    d_run2.font.size = Pt(9)
    d_run2.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)
    d_run2.italic = True

    doc.add_page_break()

    # ── FEM Visualization Gallery (before LLM analysis) ──
    if images:
        doc.add_heading("FEM Visualizations", level=1)
        gallery_note = doc.add_paragraph()
        gn_run = gallery_note.add_run(
            "The following figures were generated automatically from the Nastran "
            "model (DAT) and results (OP2) files using pyNastran and Matplotlib. "
            "These are not AI-generated — they are direct renderings of the FEM data."
        )
        gn_run.font.size = Pt(10)
        gn_run.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)
        gn_run.italic = True

        doc.add_paragraph()

        # Insert images in defined order
        ordered_images = []
        for img_name in IMAGE_ORDER:
            for img_path in images:
                if os.path.basename(img_path) == img_name:
                    ordered_images.append(img_path)
                    break
        # Add any images not in the predefined order
        for img_path in images:
            if img_path not in ordered_images:
                ordered_images.append(img_path)

        for img_path in ordered_images:
            img_name = os.path.basename(img_path)
            caption = IMAGE_CAPTIONS.get(img_name, f"Figure: {img_name}")

            try:
                # Use wider width for landscape-oriented charts
                if 'bar_chart' in img_name or 'psd_response' in img_name:
                    width = Inches(6.5)
                else:
                    width = Inches(4.5)

                doc.add_picture(img_path, width=width)
                last_p = doc.paragraphs[-1]
                last_p.alignment = WD_ALIGN_PARAGRAPH.CENTER

                cap_p = doc.add_paragraph()
                cap_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                cap_run = cap_p.add_run(caption)
                cap_run.italic = True
                cap_run.font.size = Pt(9)
                cap_run.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)

                doc.add_paragraph()  # spacing

            except Exception as e:
                doc.add_paragraph(f"[Image not available: {img_name} — {e}]")

        doc.add_page_break()

    # ── LLFEM Analysis Section ──
    llfem_header = doc.add_heading(f"{LLFEM_TAG} Analysis", level=1)

    # LLFEM badge before analysis
    badge = doc.add_paragraph()
    badge_run = badge.add_run(f"[ {LLFEM_TAG} — The following analysis was generated by AI ]")
    badge_run.bold = True
    badge_run.font.size = Pt(10)
    badge_run.font.color.rgb = RGBColor(0x25, 0x63, 0xEB)
    badge.alignment = WD_ALIGN_PARAGRAPH.CENTER

    doc.add_paragraph()

    # ── Parse LLM markdown into DOCX paragraphs ──
    lines = report_text.split('\n')
    in_list = False

    for line in lines:
        stripped = line.strip()

        if not stripped:
            if in_list:
                in_list = False
            continue

        # Section headers
        if stripped.startswith('## ') or stripped.startswith('# '):
            heading_text = stripped.lstrip('#').strip()
            level = 2 if stripped.startswith('## ') else 1
            doc.add_heading(heading_text, level=min(level + 1, 4))

        # Bold subheadings like **From fixed_base_beam.f06:**
        elif stripped.startswith('**') and stripped.endswith('**'):
            p = doc.add_paragraph()
            p.add_run(stripped.strip('*')).bold = True

        # Bold then colon: **Key:** value
        elif stripped.startswith('**') and '**' in stripped[2:]:
            p = doc.add_paragraph()
            # Split on closing **
            match = re.match(r'\*\*(.+?)\*\*(.*)$', stripped)
            if match:
                p.add_run(match.group(1)).bold = True
                rest = match.group(2).strip()
                if rest:
                    p.add_run(f" {rest}")
            else:
                p.add_run(stripped.replace('**', ''))

        # Numbered list: 1. item
        elif re.match(r'^\d+\.\s', stripped):
            text = re.sub(r'^\d+\.\s', '', stripped)
            # Handle bold within list items
            p = doc.add_paragraph(style='List Number')
            _add_formatted_runs(p, text)
            in_list = True

        # Bullet points
        elif stripped.startswith('- ') or stripped.startswith('* '):
            text = stripped[2:]
            p = doc.add_paragraph(style='List Bullet')
            _add_formatted_runs(p, text)
            in_list = True

        # Checkmark items (✅ ⚠ ❌)
        elif stripped[0] in '✅⚠❌':
            p = doc.add_paragraph()
            _add_formatted_runs(p, stripped)

        # Regular text
        else:
            p = doc.add_paragraph()
            _add_formatted_runs(p, stripped)

    # ── Footer with LLFEM stamp ──
    doc.add_paragraph()
    doc.add_paragraph()
    footer_line = doc.add_paragraph()
    footer_line.alignment = WD_ALIGN_PARAGRAPH.CENTER
    fl_run = footer_line.add_run("— " * 20)
    fl_run.font.color.rgb = RGBColor(0xD1, 0xD5, 0xDB)

    footer = doc.add_paragraph()
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    f_run = footer.add_run(
        f"{LLFEM_TAG} Report  |  Generated {now}  |  "
        f"Claude (Anthropic, temperature=0)  |  "
        f"Human review recommended"
    )
    f_run.font.size = Pt(8)
    f_run.font.color.rgb = RGBColor(0x9C, 0xA3, 0xAF)
    f_run.italic = True

    doc.save(output_path)
    return True


def _add_formatted_runs(paragraph, text):
    """Parse inline markdown bold (**text**) into Word runs."""
    parts = re.split(r'(\*\*.*?\*\*)', text)
    for part in parts:
        if part.startswith('**') and part.endswith('**'):
            run = paragraph.add_run(part[2:-2])
            run.bold = True
        else:
            paragraph.add_run(part)


# ---------------------------------------------------------------------------
# PDF Conversion
# ---------------------------------------------------------------------------
def convert_to_pdf(docx_path):
    """Convert DOCX to PDF using docx2pdf (requires Microsoft Word)."""
    pdf_path = docx_path.replace('.docx', '.pdf')

    try:
        from docx2pdf import convert
        print(f"Converting to PDF: {os.path.basename(pdf_path)}...")
        convert(docx_path, pdf_path)
        if os.path.isfile(pdf_path) and os.path.getsize(pdf_path) > 0:
            print(f"PDF generated: {pdf_path}")
            return pdf_path
        else:
            print("WARNING: PDF conversion produced empty file")
            return None
    except ImportError:
        print("WARNING: docx2pdf not installed — skipping PDF. Run: pip install docx2pdf")
        return None
    except Exception as e:
        print(f"WARNING: PDF conversion failed: {e}")
        return None


# ---------------------------------------------------------------------------
# Markdown Fallback
# ---------------------------------------------------------------------------
def write_md_report(output_path, report_text, f06_filename):
    """Write report as Markdown (fallback)."""
    now = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(f"# {LLFEM_TAG} — Nastran Simulation Report\n\n")
        f.write(f"**Generated:** {now}  \n")
        f.write(f"**F06 Files:** {f06_filename}  \n")
        f.write(f"**Generator:** Claude (Anthropic API, temperature=0)  \n")
        f.write(f"**Report Type:** {LLFEM_FULL}  \n\n")
        f.write(f"> ⚠ **{LLFEM_TAG} DISCLAIMER:** {LLFEM_DISCLAIMER}\n\n")
        f.write("---\n\n")
        f.write(report_text)
        f.write("\n")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(description="Generate LLFEM simulation report")
    parser.add_argument('--run-folder', help='Path to timestamped run folder')
    parser.add_argument('--f06', help='Path to specific F06 file')
    parser.add_argument('--output', help='Output path for report')
    parser.add_argument('--skip-llm', action='store_true', default=False,
                        help='Skip LLM call — generate report with images only (no AI analysis)')
    parser.add_argument('--docx', action='store_true', default=False,
                        help='Force DOCX output')
    parser.add_argument('--pdf', action='store_true', default=True,
                        help='Also generate PDF from DOCX (default: True)')
    parser.add_argument('--no-pdf', action='store_true', default=False,
                        help='Disable PDF generation')
    args = parser.parse_args()

    run_folder = args.run_folder or (os.path.dirname(args.f06) if args.f06 else None)
    if not run_folder:
        print("ERROR: Specify --run-folder or --f06")
        sys.exit(1)

    # Find F06 files
    if args.run_folder:
        f06_files = find_f06_files(args.run_folder)
    elif args.f06:
        f06_files = [args.f06]
    else:
        f06_files = []

    if not f06_files and not args.skip_llm:
        print("ERROR: No F06 files found (use --skip-llm for image-only report)")
        sys.exit(1)

    if f06_files:
        print(f"Found {len(f06_files)} F06 file(s)")

    # Check for captured images
    images = find_captured_images(run_folder)
    if images:
        print(f"Found {len(images)} captured FEM image(s)")

    # Auto-enable DOCX if images available
    use_docx = args.docx or len(images) > 0

    # Generate LLM report text
    if args.skip_llm:
        report_text = (
            "## LLFEM Analysis\n\n"
            "LLM analysis was skipped for this report. "
            "See FEM visualizations above for model overview.\n"
        )
        combined_filename = "N/A (--skip-llm)"
    else:
        all_content = []
        for f06_path in f06_files:
            fname = os.path.basename(f06_path)
            print(f"  Reading: {fname}")
            content = extract_f06_summary(f06_path)
            all_content.append(f"=== {fname} ===\n{content}")

        combined_content = '\n\n'.join(all_content)
        combined_filename = ', '.join(os.path.basename(f) for f in f06_files)
        report_text = generate_report(combined_content, combined_filename)

    # Write DOCX report
    if use_docx:
        output_path = args.output or os.path.join(run_folder, 'simulation_report.docx')
        success = write_docx_report(output_path, report_text, combined_filename,
                                     images, run_folder)
        if not success:
            output_path = os.path.join(run_folder, 'simulation_report.md')
            write_md_report(output_path, report_text, combined_filename)
        elif not args.no_pdf:
            convert_to_pdf(output_path)
    else:
        output_path = args.output or os.path.join(run_folder, 'simulation_report.md')
        write_md_report(output_path, report_text, combined_filename)

    # Always write .md backup
    md_path = os.path.join(run_folder, 'simulation_report.md')
    if output_path != md_path:
        write_md_report(md_path, report_text, combined_filename)
        print(f"Markdown backup: {md_path}")

    print(f"\nReport written to: {output_path}")

    # GITHUB_OUTPUT
    github_output = os.environ.get('GITHUB_OUTPUT')
    if github_output:
        with open(github_output, 'a') as f:
            f.write(f"REPORT_PATH={output_path}\n")
            f.write(f"REPORT_FORMAT={'docx' if use_docx else 'md'}\n")


if __name__ == '__main__':
    main()
